import type { Comment } from '../lib/types'

interface Seed {
  who: string
  score: number
  body: string
  replyTo?: number // index of the top-level comment this answers
}

function build(proposalId: string, baseIso: string, seeds: Seed[]): Comment[] {
  const base = Date.parse(baseIso)
  return seeds.map((s, i) => ({
    id: `cc-${proposalId}-${i}`,
    proposalId,
    userId: 'seed',
    authorName: s.who,
    parentId: s.replyTo != null ? `cc-${proposalId}-${s.replyTo}` : null,
    body: s.body,
    createdAt: new Date(base + (i + 1) * 5 * 3_600_000).toISOString(),
    score: s.score,
  }))
}

